def get_by_id(uni_id: str):
    for u in UNIVERSITIES:
        if u["id"] == uni_id:
            return u
    return None


def get_by_country(code: str):
    return [u for u in UNIVERSITIES if u["country"] == code]


def all_countries():
    codes = {}
    for u in UNIVERSITIES:
        codes[u["country"]] = codes.get(u["country"], 0) + 1
    return codes


def search(query: str, lang: str):
    q = query.lower().strip()
    if not q:
        return UNIVERSITIES
    results = []
    for u in UNIVERSITIES:
        haystack = " ".join([
            u["name"].get(lang, ""), u["name"].get("en", ""),
            u["city"].get(lang, ""), u["city"].get("en", ""),
            u["country"],
        ]).lower()
        if q in haystack:
            results.append(u)
    return results


